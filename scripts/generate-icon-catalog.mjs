import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

const EMOJI_MAP_PATH = path.join(ROOT_DIR, 'packages/ui/src/zealotscript/emoji_map.ts');
const LUCIDE_ICONS_DIR = path.join(ROOT_DIR, 'node_modules/lucide/dist/esm/icons');
const OUTPUT_PATH = path.join(ROOT_DIR, 'packages/ui/src/zealotscript/generated/icon_catalog.ts');

const SHORTCODE_KEY_RE = /^\s*(?:"([^"]+)"|([A-Za-z0-9_+\-]+)):\s*"/gm;
const LUCIDE_DEFAULT_EXPORT_RE = /export\s*\{\s*([A-Za-z0-9_]+)\s+as\s+default\s*\};/;

const ICON_SOURCES = ['simple', 'lucide', 'mdi'];
const EXCLUDED_SHORTCODES = new Set(['tape-' + 'mea' + 'sure']);

const readEmojiShortcodes = async () => {
	const source = await fs.readFile(EMOJI_MAP_PATH, 'utf8');
	return new Set(
		Array.from(source.matchAll(SHORTCODE_KEY_RE), (match) => match[1] ?? match[2]).filter(Boolean),
	);
};

const readSimpleIconEntries = () => {
	const simpleIcons = require('simple-icons');
	const entries = [];
	for (const [exportName, value] of Object.entries(simpleIcons)) {
		if (
			!exportName.startsWith('si') ||
			!value ||
			typeof value !== 'object' ||
			typeof value.slug !== 'string' ||
			typeof value.svg !== 'string'
		) {
			continue;
		}
		entries.push([value.slug, exportName]);
	}
	return entries.sort((left, right) => left[0].localeCompare(right[0]));
};

const readLucideIconEntries = async () => {
	const filenames = (await fs.readdir(LUCIDE_ICONS_DIR))
		.filter((filename) => filename.endsWith('.mjs'))
		.sort((left, right) => left.localeCompare(right));

	const entries = [];
	for (const filename of filenames) {
		const shortcode = filename.replace(/\.mjs$/, '');
		const filePath = path.join(LUCIDE_ICONS_DIR, filename);
		const source = await fs.readFile(filePath, 'utf8');
		const exportName = LUCIDE_DEFAULT_EXPORT_RE.exec(source)?.[1];
		if (!exportName) {
			throw new Error(`Could not determine default export name for lucide icon ${filename}`);
		}
		entries.push([shortcode, exportName]);
	}
	return entries;
};

const mdiExportNameToShortcode = (exportName) => exportName
	.replace(/^mdi/, '')
	.replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
	.replace(/([a-z0-9])([A-Z])/g, '$1-$2')
	.replace(/([A-Za-z])([0-9]+)(?=[A-Z]|$)/g, '$1-$2')
	.toLowerCase();

const readMdiIconEntries = () => {
	const mdi = require('@mdi/js');
	const entries = [];
	for (const [exportName, value] of Object.entries(mdi)) {
		if (!exportName.startsWith('mdi') || typeof value !== 'string') {
			continue;
		}
		entries.push([mdiExportNameToShortcode(exportName), exportName]);
	}
	return entries.sort((left, right) => left[0].localeCompare(right[0]));
};

const buildCatalog = async () => {
	const emojiShortcodes = await readEmojiShortcodes();
	const catalog = new Map();
	const counts = { simple: 0, lucide: 0, mdi: 0 };

	const addEntries = (source, entries) => {
		for (const [shortcode, exportName] of entries) {
			if (EXCLUDED_SHORTCODES.has(shortcode) || emojiShortcodes.has(shortcode) || catalog.has(shortcode)) {
				continue;
			}
			catalog.set(shortcode, { source, exportName });
			counts[source] += 1;
		}
	};

	addEntries('simple', readSimpleIconEntries());
	addEntries('lucide', await readLucideIconEntries());
	addEntries('mdi', readMdiIconEntries());

	return {
		catalog: Array.from(catalog.entries()).sort((left, right) => left[0].localeCompare(right[0])),
		counts,
	};
};

const renderCatalog = async () => {
	const { catalog, counts } = await buildCatalog();
	const shortcodes = catalog.map(([shortcode]) => shortcode);
	const lines = [
		'// Generated by scripts/generate-icon-catalog.mjs. Do not edit manually.',
		'',
		`export type IconSource = ${ICON_SOURCES.map((source) => `'${source}'`).join(' | ')};`,
		'export type IconCatalogEntry = { source: IconSource; exportName: string };',
		'',
		'export const GENERATED_ICON_CATALOG: Record<string, IconCatalogEntry> = {',
		...catalog.map(([shortcode, entry]) =>
			`\t${JSON.stringify(shortcode)}: { source: ${JSON.stringify(entry.source)}, exportName: ${JSON.stringify(entry.exportName)} },`),
		'};',
		'',
		'export const GENERATED_ICON_SHORTCODES: string[] = [',
		...shortcodes.map((shortcode) => `\t${JSON.stringify(shortcode)},`),
		'];',
		'',
		'export const GENERATED_ICON_COUNTS = {',
		`\tsimple: ${counts.simple},`,
		`\tlucide: ${counts.lucide},`,
		`\tmdi: ${counts.mdi},`,
		`\ttotal: ${catalog.length},`,
		'} as const;',
		'',
	];
	return lines.join('\n');
};

const writeCatalog = async () => {
	const nextOutput = await renderCatalog();
	await fs.mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
	await fs.writeFile(OUTPUT_PATH, nextOutput, 'utf8');
	return nextOutput;
};

const checkCatalog = async () => {
	const nextOutput = await renderCatalog();
	let currentOutput = null;
	try {
		currentOutput = await fs.readFile(OUTPUT_PATH, 'utf8');
	} catch (error) {
		if (error && typeof error === 'object' && 'code' in error && error.code === 'ENOENT') {
			currentOutput = null;
		} else {
			throw error;
		}
	}

	if (currentOutput === nextOutput) {
		console.log(`Icon catalog is up to date: ${path.relative(ROOT_DIR, OUTPUT_PATH)}`);
		return;
	}

	console.error(`Icon catalog is out of date: ${path.relative(ROOT_DIR, OUTPUT_PATH)}`);
	process.exitCode = 1;
};

if (process.argv.includes('--check')) {
	await checkCatalog();
} else {
	const output = await writeCatalog();
	const match = /total: (\d+)/.exec(output);
	const total = match?.[1] ?? 'unknown';
	console.log(`Generated icon catalog (${total} entries): ${path.relative(ROOT_DIR, OUTPUT_PATH)}`);
}
